// Real-GPU FPS benchmark of the browser build at ~1280x720 (headed Chrome/Edge, app window).
// node tools/fps.js [seconds=12] [nights=1,2,3] [outDir=docs/proof/phase-2]
// The page (?bench=S) plays a night for S seconds after a 2 s warm-up and POSTs its average FPS to /__bench.
import { spawn, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir, cpus, platform, release } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const secs = Number(process.argv[2] ?? 12);
const nights = (process.argv[3] ?? '1,2,3').split(',').map(Number);
const outDir = resolve(process.argv[4] ?? join(ROOT, 'docs/proof/phase-2'));
mkdirSync(outDir, { recursive: true });
const browser = [process.env.CHROME, 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', 'C:/Program Files/Microsoft/Edge/Application/msedge.exe',
  'C:/Program Files/Google/Chrome/Application/chrome.exe', '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/usr/bin/google-chrome', '/usr/bin/chromium'].filter(Boolean).find(existsSync);
if (!browser) { console.error('No Chrome/Edge found; set CHROME=/path/to/browser'); process.exit(1); }
const killTree = (p) => { if (platform() === 'win32') spawnSync('taskkill', ['/pid', String(p.pid), '/T', '/F'], { stdio: 'ignore' }); else p.kill('SIGKILL'); };

const results = [];
for (const night of nights) for (let attempt = 1; attempt <= 3; attempt++) { // a fresh headed window occasionally never starts rendering: retry
  const benchOut = join(mkdtempSync(join(tmpdir(), 'ddl-bench-')), 'result.json');
  const port = 8100 + Math.floor(Math.random() * 800);
  const server = spawn(process.execPath, [join(ROOT, 'tools/serve.js'), String(port)], { env: { ...process.env, BENCH_OUT: benchOut }, stdio: 'ignore' });
  await new Promise((r) => setTimeout(r, 600));
  const url = `http://localhost:${port}/web/?night=${night}&autostart&bench=${secs}&seed=7`;
  const profile = mkdtempSync(join(tmpdir(), 'ddl-prof-'));
  const b = spawn(browser, [`--app=${url}`, '--window-size=1296,759', '--window-position=40,40', `--user-data-dir=${profile}`, '--no-first-run', '--disable-background-timer-throttling', '--disable-renderer-backgrounding', '--disable-backgrounding-occluded-windows'], { stdio: 'ignore' });
  const deadline = Date.now() + (secs + 30) * 1000; // first launch of a fresh profile can be slow
  while (!existsSync(benchOut) && Date.now() < deadline) await new Promise((r) => setTimeout(r, 500));
  killTree(b); killTree(server);
  try { rmSync(profile, { recursive: true, force: true }); } catch { /* browser may still hold files */ }
  if (!existsSync(benchOut)) {
    console.error(`night ${night}: no result (timeout, attempt ${attempt})`);
    if (attempt === 3) results.push({ night, error: 'timeout x3' });
    continue;
  }
  const r = JSON.parse(readFileSync(benchOut, 'utf8'));
  results.push(r);
  console.log(`night ${night}: ${r.avg_fps} FPS avg over ${r.seconds}s at ${r.width}x${r.height} (${r.gpu})`);
  break;
}
const ok = results.every((r) => r.avg_fps >= 30);
const md = `# FPS benchmark (normal build)

Generated by \`node tools/fps.js ${secs}\`: a real (headed) browser window, the real GPU, each night auto-played for ${secs} s after a 2 s warm-up.
Requirement (Ticket-02 DoD): >= 30 FPS average at 1280x720. Result: **${ok ? 'PASS' : 'FAIL'}**.

| night | avg FPS | seconds | frames | viewport | pixel ratio |
|---|---|---|---|---|---|
${results.map((r) => (r.error ? `| ${r.night} | ${r.error} | | | | |` : `| ${r.night} | ${r.avg_fps} | ${r.seconds} | ${r.frames} | ${r.width}x${r.height} | ${r.pixel_ratio} |`)).join('\n')}

Machine: ${cpus()[0]?.model ?? '?'} · ${platform()} ${release()} · GPU: ${results.find((r) => r.gpu)?.gpu ?? '?'}
Browser: ${results.find((r) => r.ua)?.ua ?? '?'}
`;
writeFileSync(join(outDir, 'fps.md'), md);
console.log(`${ok ? 'PASS' : 'FAIL'} -> ${join(outDir, 'fps.md')}`);
process.exit(ok ? 0 : 1);
